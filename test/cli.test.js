import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { makeInstall, makeTempDir, presetPatch } from './helpers.js';

const BIN = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'bin', 'preset-rules.js');
const RULE = 'presets = all; entry = id: time-context; action = hide()';

function fixtures(t, rules = RULE) {
  const dir = makeTempDir(t);
  const install = makeInstall(t, {
    'presets/alpha.patch.yml': presetPatch('alpha', 1, [
      { id: 'persona', name: '@deepseek-ai/dsh-persona' },
      { id: 'time-context', name: '@deepseek-ai/dsh-time-context' },
    ]),
  });
  const rulesPath = path.join(dir, 'preset-rules.rules');
  if (rules !== null) fs.writeFileSync(rulesPath, rules);
  const targetPath = path.join(dir, 'out', 'cordis.patch.yml');
  return { dir, install, rulesPath, targetPath };
}

const run = (args) => spawnSync(process.execPath, [BIN, ...args], { encoding: 'utf8' });

test('--check prints the report and writes nothing', (t) => {
  const { install, rulesPath, targetPath } = fixtures(t);
  const result = run(['--check', '--source', install, '--rules', rulesPath, '--target', targetPath]);

  assert.equal(result.status, 0, result.stderr);
  assert.match(result.stdout, /^preset-rules: check \(no write\)$/m);
  assert.match(result.stdout, /^  alpha    : 2 -> 1 {3}\(- time-context\)$/m);
  assert.match(result.stdout, /^would write 1 entry \(/m);
  assert.equal(fs.existsSync(targetPath), false);
});

test('--apply writes the generated file', (t) => {
  const { install, rulesPath, targetPath } = fixtures(t);
  const result = run(['--apply', '--source', install, '--rules', rulesPath, '--target', targetPath]);

  assert.equal(result.status, 0, result.stderr);
  assert.match(result.stdout, /^preset-rules: written$/m);
  assert.ok(fs.readFileSync(targetPath, 'utf8').startsWith('# generated by dsh-preset-rules 0.1.0'));
});

test('--json reports the same run as data', (t) => {
  const { install, rulesPath, targetPath } = fixtures(t);
  const result = run(['--check', '--json', '--source', install, '--rules', rulesPath, '--target', targetPath]);

  assert.equal(result.status, 0, result.stderr);
  const payload = JSON.parse(result.stdout);
  assert.equal(payload.action, 'would-write');
  assert.equal(payload.presets[0].presetId, 'alpha');
  assert.deepEqual(payload.presets[0].hidden, ['time-context']);
  assert.deepEqual(payload.diagnostics, []);
});

test('a rule error exits 1 with a position', (t) => {
  const { install, rulesPath, targetPath } = fixtures(t, 'presets = all; entry = *; action = nope()');
  const result = run(['--check', '--source', install, '--rules', rulesPath, '--target', targetPath]);

  assert.equal(result.status, 1);
  assert.match(result.stderr, /preset-rules\.rules:1:\d+: error: unknown action "nope"/);
  assert.equal(result.stdout, '');
});

test('an unknown option exits 2 with usage', () => {
  const result = run(['--wat']);
  assert.equal(result.status, 2);
  assert.match(result.stderr, /unknown option "--wat"/);
  assert.match(result.stderr, /Usage:/);
});

test('--help prints usage and exits 0', () => {
  const result = run(['--help']);
  assert.equal(result.status, 0);
  assert.match(result.stdout, /Usage:/);
});

test('--init writes the starter rule file exactly once', (t) => {
  const dir = makeTempDir(t);
  const rulesPath = path.join(dir, 'preset-rules.rules');

  const first = run(['--init', '--rules', rulesPath]);
  assert.equal(first.status, 0, first.stderr);
  assert.match(first.stdout, /created/);

  const text = fs.readFileSync(rulesPath, 'utf8');
  assert.match(text, /^# Example rule file for dsh-preset-rules\.$/m);
  assert.match(text, /^presets = all; entry = id: time-context; action = hide\(\)$/m);

  const second = run(['--init', '--rules', rulesPath]);
  assert.equal(second.status, 0);
  assert.match(second.stdout, /already exists/);
  assert.equal(fs.readFileSync(rulesPath, 'utf8'), text);
});
