import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';

import { GenerateError, generate, validateRendered } from '../src/generate.js';
import { formatReport } from '../src/report.js';
import { RuleError } from '../src/rules.js';
import { renderPatch } from '../src/render.js';
import { loadEntryList } from '../src/yaml.js';
import { PRESET_PLUGIN, makeInstall, makeTempDir, presetPatch } from './helpers.js';

const RULE = 'presets = all; entry = id: time-context; action = hide()';

function setup(t, options = {}) {
  const dir = makeTempDir(t);

  const install = makeInstall(t, options.files ?? {
    'presets/alpha.patch.yml': presetPatch('alpha', 1, [
      { id: 'persona', name: '@deepseek-ai/dsh-persona' },
      { id: 'time-context', name: '@deepseek-ai/dsh-time-context' },
    ]),
    'presets/beta.patch.yml': presetPatch('beta', 2, [{ id: 'persona', name: '@deepseek-ai/dsh-persona' }]),
  });

  const rulesPath = path.join(dir, 'preset-rules.rules');
  if (options.rules !== undefined) fs.writeFileSync(rulesPath, options.rules);

  const targetPath = path.join(dir, 'out', 'cordis.patch.yml');
  if (options.target !== undefined) {
    fs.mkdirSync(path.dirname(targetPath), { recursive: true });
    fs.writeFileSync(targetPath, options.target);
  }

  return { dir, install, rulesPath, targetPath };
}

test('writes a generated patch for the preset that changed', (t) => {
  const { install, rulesPath, targetPath } = setup(t, { rules: RULE });
  const result = generate({ rulesPath, targetPath, webAppDir: install });

  assert.equal(result.action, 'written');
  const text = fs.readFileSync(targetPath, 'utf8');
  assert.ok(text.startsWith('# generated by dsh-preset-rules 0.1.0 — do not edit\n'));

  const parsed = loadEntryList(text);
  assert.equal(parsed.length, 1, 'only the changed preset is emitted');
  assert.equal(parsed[0].config.id, 'alpha');
  assert.equal(parsed[0].config.order, 1, 'upstream metadata survives');
  assert.deepEqual(parsed[0].config.plugins.map((row) => row.id), ['persona']);
  assert.deepEqual(
    result.results.map((item) => [item.presetId, item.changed]),
    [
      ['alpha', true],
      ['beta', false],
    ],
  );
});

test('a second run with the same inputs is a no-op', (t) => {
  const { install, rulesPath, targetPath } = setup(t, { rules: RULE });
  const first = generate({ rulesPath, targetPath, webAppDir: install });
  const before = fs.readFileSync(targetPath, 'utf8');

  const second = generate({ rulesPath, targetPath, webAppDir: install });
  assert.equal(first.action, 'written');
  assert.equal(second.action, 'unchanged');
  assert.equal(fs.readFileSync(targetPath, 'utf8'), before);
});

test('check mode reports without touching the disk', (t) => {
  const { install, rulesPath, targetPath } = setup(t, { rules: RULE });
  const result = generate({ rulesPath, targetPath, webAppDir: install, mode: 'check' });

  assert.equal(result.action, 'would-write');
  assert.equal(fs.existsSync(targetPath), false);
  assert.match(formatReport(result), /would write 1 entry/);
});

test('off mode does nothing at all', (t) => {
  const { install, rulesPath, targetPath } = setup(t, { rules: RULE });
  const result = generate({ rulesPath, targetPath, webAppDir: install, mode: 'off' });
  assert.equal(result.action, 'off');
  assert.equal(fs.existsSync(targetPath), false);
});

test('an unknown mode is rejected', () => {
  assert.throws(() => generate({ rulesPath: 'x', targetPath: 'y', mode: 'write' }), GenerateError);
});

test('refuses to overwrite a file it did not write', (t) => {
  const handwritten = '# my own patch\n- id: something\n';
  const { install, rulesPath, targetPath } = setup(t, { rules: RULE, target: handwritten });

  assert.throws(
    () => generate({ rulesPath, targetPath, webAppDir: install }),
    (error) => error instanceof GenerateError && /refusing to overwrite/.test(error.message),
  );
  assert.equal(fs.readFileSync(targetPath, 'utf8'), handwritten);
});

test('a rule error leaves the existing output untouched', (t) => {
  const { install, rulesPath, targetPath } = setup(t, { rules: RULE });
  generate({ rulesPath, targetPath, webAppDir: install });
  const before = fs.readFileSync(targetPath, 'utf8');

  fs.writeFileSync(rulesPath, 'presets = all; entry = id: x; action = set(config.a, 1)');
  assert.throws(
    () => generate({ rulesPath, targetPath, webAppDir: install }),
    (error) => error instanceof RuleError && /not supported in 0.1/.test(error.message),
  );
  assert.equal(fs.readFileSync(targetPath, 'utf8'), before);
});

test('an upstream failure leaves the existing output untouched', (t) => {
  const { install, rulesPath, targetPath } = setup(t, { rules: RULE });
  generate({ rulesPath, targetPath, webAppDir: install });
  const before = fs.readFileSync(targetPath, 'utf8');

  const brokenInstall = makeInstall(t, { 'cordis.patch.yml': ['- insert:', '    - id: x', "      name: 'y'", ''].join('\n') });
  assert.throws(
    () => generate({ rulesPath, targetPath, webAppDir: brokenInstall }),
    (error) => error instanceof GenerateError && /no agent-preset declarations/.test(error.message),
  );
  assert.equal(fs.readFileSync(targetPath, 'utf8'), before);
});

test('deleting the rules file clears a previously generated patch', (t) => {
  const { install, rulesPath, targetPath } = setup(t, { rules: RULE });
  generate({ rulesPath, targetPath, webAppDir: install });

  fs.rmSync(rulesPath);
  const result = generate({ rulesPath, targetPath, webAppDir: install });
  assert.equal(result.action, 'written');
  assert.ok(fs.readFileSync(targetPath, 'utf8').endsWith('\n[]\n'));
  assert.match(formatReport(result), /cleared the generated patch/);
});

test('no rules and no target means no file is created', (t) => {
  const { install, rulesPath, targetPath } = setup(t);
  const result = generate({ rulesPath, targetPath, webAppDir: install });

  assert.equal(result.action, 'unchanged');
  assert.equal(fs.existsSync(targetPath), false);
});

test('source warnings are merged into the diagnostics', (t) => {
  const { install, rulesPath, targetPath } = setup(t, {
    rules: 'presets = all; entry = id: persona; action = hide()',
    files: {
      'presets/alpha.patch.yml': presetPatch('alpha', 1, [{ id: 'persona', name: '@deepseek-ai/dsh-persona' }]),
      'presets/broken.patch.yml': '- insert: [\n',
    },
  });

  const result = generate({ rulesPath, targetPath, webAppDir: install });
  assert.equal(result.diagnostics.length, 1);
  assert.match(result.diagnostics[0].message, /broken\.patch\.yml/);
  assert.match(formatReport(result), /warning: cannot parse presets\/broken\.patch\.yml/);
});

test('validateRendered rejects a surviving hidden row', () => {
  const results = [{ presetId: 'alpha', changed: true, rows: [{ id: 'persona' }], hidden: ['time-context'] }];
  const text = renderPatch({
    entries: [
      {
        id: 'preset-alpha',
        name: PRESET_PLUGIN,
        config: { id: 'alpha', order: 1, plugins: [{ id: 'time-context' }] },
      },
    ],
    generator: { name: 'dsh-preset-rules', version: '0.1.0' },
    source: { name: '@deepseek-ai/dsh-web-app', version: 'x' },
    sourceHash: 'sha256:x',
    rulesHash: 'none',
  });

  assert.throws(() => validateRendered(text, results), /hidden row "time-context" survived/);
});

test('validateRendered rejects a row count mismatch', () => {
  const results = [{ presetId: 'alpha', changed: true, rows: [{ id: 'persona' }], hidden: [] }];
  const text = renderPatch({
    entries: [
      {
        id: 'preset-alpha',
        name: PRESET_PLUGIN,
        config: {
          id: 'alpha',
          order: 1,
          plugins: [{ id: 'persona' }, { id: 'extra' }],
        },
      },
    ],
    generator: { name: 'dsh-preset-rules', version: '0.1.0' },
    source: { name: '@deepseek-ai/dsh-web-app', version: 'x' },
    sourceHash: 'sha256:x',
    rulesHash: 'none',
  });

  assert.throws(() => validateRendered(text, results), /rendered 2 rows, expected 1/);
});

test('formatReport prints the documented check shape', () => {
  const text = formatReport({
    action: 'would-write',
    targetPath: 'C:\\out\\cordis.patch.yml',
    source: { version: '0.2.2-rc.1', origin: 'asar' },
    bytes: 18877,
    results: [
      { presetId: 'alpha', changed: true, originalRows: [1, 2], rows: [1], hidden: ['time-context'] },
      { presetId: 'minimal', changed: false, originalRows: [1, 2, 3], rows: [1, 2, 3], hidden: [] },
    ],
    diagnostics: [{ level: 'warning', message: 'careful', line: 3 }],
  });

  assert.match(text, /^preset-rules: check \(no write\)$/m);
  assert.match(text, /^  alpha    : 2 -> 1 {3}\(- time-context\)$/m);
  assert.match(text, /^  minimal  : 3 rows, unchanged$/m);
  assert.match(text, /^source: 0\.2\.2-rc\.1 \(asar\)$/m);
  assert.match(text, /^would write 1 entry \(18\.4 KB\)$/m);
  assert.match(text, /^warning: careful \(line 3\)$/m);
});
