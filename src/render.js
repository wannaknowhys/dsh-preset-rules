/**
 * Render the generated patch file.
 *
 * The output must be byte-stable for identical inputs: no timestamps, no host
 * names, no absolute paths. Only versions and content hashes appear, so a
 * no-op start compares equal and skips the write.
 */

import { createHash } from 'node:crypto';

import { dumpEntries } from './yaml.js';

/** First-line marker used to tell our file from a hand-written one. */
export const GENERATED_MARKER = '# generated by dsh-preset-rules';

/** `sha256:<hex>` for any UTF-8 text. */
export function hashText(text) {
  return `sha256:${createHash('sha256').update(text, 'utf8').digest('hex')}`;
}

/** Whether an existing file was produced by this generator. */
export function isGenerated(text) {
  return typeof text === 'string' && text.startsWith(GENERATED_MARKER);
}

/**
 * Render the complete patch file.
 * @param {object} input
 * @param {Array<object>} input.entries preset patch rows to write
 * @param {{name: string, version: string}} input.generator
 * @param {{name: string, version?: string}} input.source upstream package identity
 * @param {string} input.sourceHash content hash of the upstream preset files
 * @param {string} input.rulesHash content hash of the rules file, or `none`
 * @returns {string} YAML text ending with a newline
 */
export function renderPatch({ entries, generator, source, sourceHash, rulesHash }) {
  const header = [
    `${GENERATED_MARKER} ${generator.version} — do not edit`,
    `# source: ${source.name} ${source.version ?? 'unknown'}`,
    `# source-hash: ${sourceHash}`,
    `# rules-hash: ${rulesHash}`,
  ];
  const body = entries.length === 0 ? '[]\n' : dumpEntries(entries);
  return `${header.join('\n')}\n${body}`;
}
